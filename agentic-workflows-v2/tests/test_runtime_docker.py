def test_factory_docker_profile_passthrough(tmp_path):
    runtime = create_runtime(
        {
            "runtime": "docker",
            "container_image": "alpine:3.20",
            "timeout_seconds": 7,
            "memory_limit": "128m",
            "cpu_limit": 2.0,
            "network_disabled": False,
        }
    )

    assert isinstance(runtime, DockerRuntime)
    assert runtime._timeout_seconds == 7
    args = list(runtime._docker_command("true", tmp_path, "agentic-cfg"))
    assert "alpine:3.20" in args
    assert args[args.index("--memory") + 1] == "128m"
    assert "--cpus=2.0" in args
    assert "--network=none" not in args


def test_factory_normalizes_runtime_name():
    assert isinstance(create_runtime({"runtime": "  DOCKER  "}), DockerRuntime)
    assert isinstance(create_runtime({"runtime": "Subprocess"}), SubprocessRuntime)


def test_factory_rejects_unknown_runtime():
    with pytest.raises(ValueError, match="Unsupported runtime 'firecracker'"):
        create_runtime({"runtime": "firecracker"})


def test_execution_error_message_marks_empty_stderr():
    err = RuntimeExecutionError("run thing", 3, "out", "   ")

    assert "exit code 3" in str(err)
    assert "<empty>" in str(err)
    assert (err.command, err.exit_code, err.stdout) == ("run thing", 3, "out")
