async def test_docker_execute_success_records_result(monkeypatch, tmp_path):
    _docker_available(monkeypatch)
    proc = _FakeProc(stdout=b"ok\n", stderr=b"", returncode=0)
    captured = _install_fake_exec(monkeypatch, proc)
    runtime = DockerRuntime()

    # No explicit setup(): execute() must self-setup (auto-setup branch).
    result = await runtime.execute("echo ok", workdir=tmp_path)

    assert result.exit_code == 0
    assert result.stdout == "ok\n"
    assert result.command == "echo ok"
    assert result.workdir == str(tmp_path.resolve())
    assert captured["argv"][:2] == ["docker", "run"]
    name = captured["argv"][captured["argv"].index("--name") + 1]
    assert name.startswith("agentic-")
    # Bookkeeping: recorded, and no container left marked active.
    assert len((await runtime.collect_artifacts())["executions"]) == 1
    assert runtime._active_containers == []


async def test_docker_execute_nonzero_exit_raises(monkeypatch, tmp_path):
    _docker_available(monkeypatch)
    proc = _FakeProc(stdout=b"", stderr=b"boom", returncode=5)
    _install_fake_exec(monkeypatch, proc)
    runtime = DockerRuntime()

    with pytest.raises(RuntimeExecutionError) as exc:
        await runtime.execute("false", workdir=tmp_path)

    assert exc.value.exit_code == 5
    assert exc.value.stderr == "boom"
    # The failed execution is still recorded for artifact collection.
    assert len((await runtime.collect_artifacts())["executions"]) == 1


async def test_docker_execute_timeout_kills_container(monkeypatch, tmp_path):
    _docker_available(monkeypatch)
    kills = _record_kills(monkeypatch)
    proc = _FakeProc(stdout=b"partial-out", stderr=b"partial-err", hang_first=True)
    captured = _install_fake_exec(monkeypatch, proc)
    runtime = DockerRuntime(timeout_seconds=1)

    with pytest.raises(RuntimeExecutionError) as exc:
        await runtime.execute("sleep 999", workdir=tmp_path)

    # Timeout is surfaced as the Docker kill exit code with a marked stderr.
    assert exc.value.exit_code == 137
    assert exc.value.stderr.startswith("[TIMEOUT after 1s]")
    assert "partial-err" in exc.value.stderr
    assert exc.value.stdout == "partial-out"
    # The hung container was force-killed by name, and the retry collected
    # partial output (two communicate() calls total).
    expected_name = captured["argv"][captured["argv"].index("--name") + 1]
    assert kills == [expected_name]
    assert proc.calls == 2
    assert runtime._active_containers == []


