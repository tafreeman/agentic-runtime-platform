def test_docker_command_hardening_defaults(tmp_path):
    runtime = DockerRuntime()

    args = list(runtime._docker_command("echo hi", tmp_path, "agentic-abc123"))

    assert args[:2] == ["docker", "run"]
    assert "--rm" in args
    assert args[args.index("--name") + 1] == "agentic-abc123"
    assert args[args.index("-w") + 1] == "/workspace"
    assert args[args.index("-v") + 1] == f"{tmp_path}:/workspace"
    assert args[args.index("--memory") + 1] == "512m"
    assert "--cpus=1.0" in args
    assert "--network=none" in args
    # Image comes after every hardening flag, then the shell invocation.
    assert args[-4] == DEFAULT_DOCKER_IMAGE
    assert args[-3:] == _shell_tail("echo hi")


def test_docker_command_network_opt_out_removes_isolation(tmp_path):
    runtime = DockerRuntime(network_disabled=False)

    args = list(runtime._docker_command("true", tmp_path, "agentic-net"))

    assert "--network=none" not in args


def test_docker_command_reflects_custom_limits(tmp_path):
    runtime = DockerRuntime(
        container_image="alpine:3.20",
        memory_limit="256m",
        cpu_limit=0.5,
    )

    args = list(runtime._docker_command("true", tmp_path, "agentic-lim"))

    assert args[args.index("--memory") + 1] == "256m"
