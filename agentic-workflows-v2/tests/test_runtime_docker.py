async def test_docker_cleanup_kills_active_and_removes_workdirs(monkeypatch):
    kills = _record_kills(monkeypatch)
    runtime = DockerRuntime()
    runtime._is_setup = True
    runtime._active_containers.append("agentic-orphan")
    managed = runtime._resolve_workdir(None)
    assert managed.exists()

    await runtime.cleanup()

    assert kills == ["agentic-orphan"]
    assert runtime._active_containers == []
    assert runtime._managed_workdirs == []
    assert not managed.exists()
    assert runtime._is_setup is False


async def test_docker_collect_artifacts_reports_image():
    runtime = DockerRuntime(container_image="alpine:3.20")

    artifacts = await runtime.collect_artifacts()

    assert artifacts["container_image"] == "alpine:3.20"
    assert artifacts["executions"] == []
    assert artifacts["workdirs"] == []


def test_docker_resolve_workdir_explicit_path_not_managed(tmp_path):
    runtime = DockerRuntime()

    resolved = runtime._resolve_workdir(tmp_path)

    assert resolved == tmp_path.resolve()
    # Caller-owned directories are never scheduled for cleanup.
    assert runtime._managed_workdirs == []


async def test_subprocess_execute_explicit_workdir_passthrough(tmp_path):
    runtime = SubprocessRuntime()
    try:
        result = await runtime.execute("echo hi", workdir=tmp_path)
    finally:
        await runtime.cleanup()

    assert result.workdir == str(tmp_path)
    assert tmp_path.exists(), "explicit workdir must survive cleanup"


