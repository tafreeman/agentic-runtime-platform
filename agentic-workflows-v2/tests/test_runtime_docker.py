"""DockerRuntime hardening-contract tests (offline, no Docker required).

Companion to ``tests/test_runtime.py``, which covers ``SubprocessRuntime`` and
the factory basics. This module exercises the previously untested
``DockerRuntime`` surface — the isolation boundary documented in
``engine/runtime.py``:

* ``_docker_command`` flag construction — named container, ``--rm``,
  ``/workspace`` mount, ``--memory``/``--cpus`` limits, and the
  ``--network=none`` isolation toggle. These flags ARE the hardening; a
  regression here silently weakens sandboxing, so they are asserted directly.
* ``execute()`` happy path, non-zero exit, and the timeout kill-path
  (container force-kill, partial-output recovery, synthetic exit code 137,
  ``[TIMEOUT after Ns]`` stderr prefix) via a faked
  ``asyncio.create_subprocess_exec`` — no Docker daemon needed.
* ``cleanup()`` force-kills still-active containers and removes managed
  workdirs; ``collect_artifacts()`` reports the container image.
* ``create_runtime`` profile passthrough, name normalization, and the
  unsupported-runtime error branch.

All tests are deterministic and key-free; no subprocess is ever spawned.

Provenance: AI-generated by the Daily Test Improver scheduled run
(2026-07-31); reviewed gates: ruff + full unit suite + coverage delta.
"""

from __future__ import annotations

import asyncio
import os

import pytest

from agentic_v2.engine.runtime import (
    DEFAULT_DOCKER_IMAGE,
    DockerRuntime,
    RuntimeExecutionError,
    SubprocessRuntime,
    create_runtime,
)


class _FakeProc:
    """Minimal stand-in for an ``asyncio.subprocess.Process``.

    ``hang_first=True`` makes the first ``communicate()`` call block until
    cancelled (driving the ``wait_for`` timeout path); the retry call then
    returns the configured output, mimicking partial output collected after
    ``docker kill``.
    """

    def __init__(
        self,
        stdout: bytes = b"",
        stderr: bytes = b"",
        returncode: int = 0,
        hang_first: bool = False,
    ) -> None:
        self.returncode = returncode
        self.calls = 0
        self._stdout = stdout
        self._stderr = stderr
        self._hang_first = hang_first

    async def communicate(self) -> tuple[bytes, bytes]:
        self.calls += 1
        if self._hang_first and self.calls == 1:
            await asyncio.sleep(3600)
        return self._stdout, self._stderr


def _install_fake_exec(monkeypatch, proc: _FakeProc) -> dict:
    """Patch ``asyncio.create_subprocess_exec`` and capture the argv used."""
    captured: dict = {}

    async def _fake_exec(*args, **kwargs):
        captured["argv"] = [str(a) for a in args]
        return proc

    monkeypatch.setattr(asyncio, "create_subprocess_exec", _fake_exec)
    return captured


def _docker_available(monkeypatch) -> None:
    monkeypatch.setattr(
        "agentic_v2.engine.runtime.shutil.which", lambda _name: "/usr/bin/docker"
    )


def _record_kills(monkeypatch) -> list[str]:
    kills: list[str] = []

    async def _fake_kill(name: str) -> None:
        kills.append(name)

    monkeypatch.setattr(DockerRuntime, "_kill_container", staticmethod(_fake_kill))
    return kills


def _shell_tail(cmd: str) -> list[str]:
    return ["cmd", "/c", cmd] if os.name == "nt" else ["/bin/sh", "-lc", cmd]


